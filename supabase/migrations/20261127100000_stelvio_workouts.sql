-- STELVIO 공용 워크아웃 — 구글시트(Workouts / WorkoutSegments)를 Supabase 로 이전 (2026-11-27)
-- 시트의 id 를 그대로 보존(그룹방·훈련 스케줄이 workoutId 로 참조). 응답 모양은 기존 GAS API 와 동일하게 맞춘다.
-- 테이블은 RLS 만 켜고 정책을 두지 않는다 → 아래 RPC(SECURITY DEFINER)로만 접근.

CREATE TABLE IF NOT EXISTS public.stelvio_workouts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  author text NOT NULL DEFAULT '',           -- 카테고리(예: 'Endurance(Z2)')
  total_seconds integer NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT '보이기',      -- '보이기' | '숨기기' | 비공개 목록명
  publish_date date,
  password text NOT NULL DEFAULT '',
  created_by uuid REFERENCES public.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.stelvio_workout_segments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workout_id bigint NOT NULL REFERENCES public.stelvio_workouts(id) ON DELETE CASCADE,
  ord integer NOT NULL DEFAULT 0,
  label text NOT NULL DEFAULT '',
  segment_type text NOT NULL DEFAULT 'interval',
  duration_sec integer NOT NULL DEFAULT 0,
  target_type text NOT NULL DEFAULT 'ftp_pct',
  target_value text NOT NULL DEFAULT '0',     -- 숫자 또는 "100/120"(dual, ftp_pctz)
  ramp text NOT NULL DEFAULT 'none',
  ramp_to_value numeric
);
CREATE INDEX IF NOT EXISTS idx_stelvio_workout_segments_workout ON public.stelvio_workout_segments(workout_id, ord);

ALTER TABLE public.stelvio_workouts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stelvio_workout_segments ENABLE ROW LEVEL SECURITY;

-- 세그먼트 행 → 기존 시트 응답 모양(target_value 는 숫자면 number)
CREATE OR REPLACE FUNCTION public._stelvio_segments_json(p_id bigint)
RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'id', s.id, 'workout_id', s.workout_id, 'ord', s.ord, 'label', s.label,
    'segment_type', s.segment_type, 'duration_sec', s.duration_sec, 'target_type', s.target_type,
    'target_value', CASE WHEN s.target_value ~ '^-?\d+(\.\d+)?$' THEN to_jsonb(s.target_value::numeric) ELSE to_jsonb(s.target_value) END,
    'ramp', s.ramp, 'ramp_to_value', s.ramp_to_value) ORDER BY s.ord, s.id), '[]'::jsonb)
  FROM stelvio_workout_segments s WHERE s.workout_id = p_id;
$$;
REVOKE ALL ON FUNCTION public._stelvio_segments_json(bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public._stelvio_workout_json(w stelvio_workouts)
RETURNS jsonb
LANGUAGE sql IMMUTABLE SET search_path = public
AS $$
  SELECT jsonb_build_object('id', w.id, 'title', w.title, 'description', w.description, 'author', w.author,
    'created_at', w.created_at, 'total_seconds', w.total_seconds, 'status', w.status,
    'publish_date', w.publish_date, 'password', NULLIF(w.password, ''));
$$;
REVOKE ALL ON FUNCTION public._stelvio_workout_json(stelvio_workouts) FROM PUBLIC, anon, authenticated;

-- 목록 (비로그인 화면·Cloud Functions 도 읽으므로 anon 허용 — 기존 GAS 웹앱도 공개였음)
CREATE OR REPLACE FUNCTION public.fn_stelvio_workouts_list()
RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT jsonb_build_object('success', true, 'items',
    COALESCE(jsonb_agg(public._stelvio_workout_json(w) ORDER BY w.id), '[]'::jsonb))
  FROM stelvio_workouts w;
$$;

CREATE OR REPLACE FUNCTION public.fn_stelvio_workout_get(p_id bigint)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public
AS $$
DECLARE w stelvio_workouts; item jsonb;
BEGIN
  SELECT * INTO w FROM stelvio_workouts WHERE id = p_id;
  IF NOT FOUND THEN RETURN jsonb_build_object('success', false, 'error', '워크아웃을 찾을 수 없습니다.'); END IF;
  item := public._stelvio_workout_json(w) || jsonb_build_object('segments', public._stelvio_segments_json(p_id));
  RETURN jsonb_build_object('success', true, 'item', item, 'workout', item);
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_stelvio_workout_segments(p_id bigint)
RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT jsonb_build_object('success', true, 'segments', public._stelvio_segments_json(p_id));
$$;

-- 생성: 로그인 사용자 누구나(기존 시트 정책과 동일). 세그먼트까지 한 번에 저장 + total_seconds 계산
CREATE OR REPLACE FUNCTION public.fn_stelvio_workout_create(p_workout jsonb, p_segments jsonb DEFAULT '[]'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_title text := btrim(COALESCE(p_workout->>'title', ''));
  v_id bigint; v_total integer; v_n integer;
BEGIN
  IF v_uid IS NULL THEN RETURN jsonb_build_object('success', false, 'error', 'unauthenticated'); END IF;
  IF v_title = '' THEN RETURN jsonb_build_object('success', false, 'error', '제목이 필요합니다.'); END IF;
  IF jsonb_typeof(COALESCE(p_segments, '[]'::jsonb)) <> 'array' OR jsonb_array_length(COALESCE(p_segments, '[]'::jsonb)) > 500 THEN
    RETURN jsonb_build_object('success', false, 'error', '세그먼트 형식이 올바르지 않거나 너무 많습니다.');
  END IF;

  INSERT INTO stelvio_workouts (title, description, author, status, publish_date, password, created_by)
  VALUES (v_title, COALESCE(p_workout->>'description', ''), COALESCE(p_workout->>'author', ''),
          COALESCE(NULLIF(p_workout->>'status', ''), '보이기'), NULLIF(p_workout->>'publish_date', '')::date,
          COALESCE(p_workout->>'password', ''), v_uid)
  RETURNING id INTO v_id;

  INSERT INTO stelvio_workout_segments (workout_id, ord, label, segment_type, duration_sec, target_type, target_value, ramp, ramp_to_value)
  SELECT v_id, (e.ord - 1)::int, COALESCE(e.s->>'label', ''), COALESCE(NULLIF(e.s->>'segment_type', ''), 'interval'),
         GREATEST(1, COALESCE(NULLIF(e.s->>'duration_sec', '')::numeric, 300))::int,
         COALESCE(NULLIF(e.s->>'target_type', ''), 'ftp_pct'), COALESCE(e.s->>'target_value', '0'),
         CASE WHEN e.s->>'ramp' = 'linear' THEN 'linear' ELSE 'none' END,
         CASE WHEN e.s->>'ramp' = 'linear' THEN NULLIF(e.s->>'ramp_to_value', '')::numeric END
  FROM jsonb_array_elements(COALESCE(p_segments, '[]'::jsonb)) WITH ORDINALITY AS e(s, ord);
  GET DIAGNOSTICS v_n = ROW_COUNT;

  SELECT COALESCE(SUM(duration_sec), 0) INTO v_total FROM stelvio_workout_segments WHERE workout_id = v_id;
  UPDATE stelvio_workouts SET total_seconds = v_total WHERE id = v_id;
  RETURN jsonb_build_object('success', true, 'workoutId', v_id, 'id', v_id, 'addedSegments', v_n);
END;
$$;

-- 수정/삭제: 관리자·부관리자 또는 작성자(이전된 기존 워크아웃은 작성자 없음 → 관리자만)
CREATE OR REPLACE FUNCTION public._stelvio_workout_can_edit(p_id bigint)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT auth.uid() IS NOT NULL AND (
    public.fn_is_admin() OR public.fn_is_sub_admin()
    OR EXISTS (SELECT 1 FROM stelvio_workouts WHERE id = p_id AND created_by = auth.uid()));
$$;
REVOKE ALL ON FUNCTION public._stelvio_workout_can_edit(bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.fn_stelvio_workout_update(p_id bigint, p_workout jsonb)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF NOT public._stelvio_workout_can_edit(p_id) THEN RETURN jsonb_build_object('success', false, 'error', '수정 권한이 없습니다.'); END IF;
  IF btrim(COALESCE(p_workout->>'title', '')) = '' THEN RETURN jsonb_build_object('success', false, 'error', '제목이 필요합니다.'); END IF;
  UPDATE stelvio_workouts SET
    title = btrim(p_workout->>'title'), description = COALESCE(p_workout->>'description', ''),
    author = COALESCE(p_workout->>'author', ''), status = COALESCE(NULLIF(p_workout->>'status', ''), '보이기'),
    publish_date = NULLIF(p_workout->>'publish_date', '')::date, password = COALESCE(p_workout->>'password', ''),
    updated_at = now()
  WHERE id = p_id;
  IF NOT FOUND THEN RETURN jsonb_build_object('success', false, 'error', '워크아웃을 찾을 수 없습니다.'); END IF;
  RETURN jsonb_build_object('success', true);
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_stelvio_workout_delete(p_id bigint)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF NOT public._stelvio_workout_can_edit(p_id) THEN RETURN jsonb_build_object('success', false, 'error', '삭제 권한이 없습니다.'); END IF;
  DELETE FROM stelvio_workouts WHERE id = p_id;
  RETURN jsonb_build_object('success', true);
END;
$$;

REVOKE ALL ON FUNCTION public.fn_stelvio_workouts_list(), public.fn_stelvio_workout_get(bigint), public.fn_stelvio_workout_segments(bigint),
  public.fn_stelvio_workout_create(jsonb, jsonb), public.fn_stelvio_workout_update(bigint, jsonb), public.fn_stelvio_workout_delete(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.fn_stelvio_workouts_list(), public.fn_stelvio_workout_get(bigint), public.fn_stelvio_workout_segments(bigint) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.fn_stelvio_workout_create(jsonb, jsonb), public.fn_stelvio_workout_update(bigint, jsonb), public.fn_stelvio_workout_delete(bigint) TO authenticated;
